import { check } from "../../scripts/check.js";
import * as q from "./questions.js";

check(q.swap, [[[[1, 2, 3], 0, 2], [3, 2, 1]], [[[5, 6], 1, 1], [5, 6]], [[[7, 8], 0, 1], [8, 7]], [[[9], 0, 0], [9]]]);
check(q.reverseInPlace, [[[[1, 2, 3, 4]], [4, 3, 2, 1]], [[[1, 2, 3]], [3, 2, 1]], [[[]], []], [[[7]], [7]], [[[-1, 0, 1]], [1, 0, -1]]]);
check(q.isPalindromeArray, [[[[1, 2, 1]], true], [[[1, 2]], false], [[[]], true], [[[5]], true], [[[1, 2, 2, 1]], true], [[[1, 2, 3, 1]], false]]);
check(q.moveZerosToEnd, [
  [[[0, 1, 0, 3, 12]], [1, 3, 12, 0, 0]],
  [[[0, 0]], [0, 0]],
  [[[]], []],
  [[[1, 2, 3]], [1, 2, 3]],
  [[[0]], [0]],
  [[[4, 0, -2, 0, 5]], [4, -2, 5, 0, 0]],
]);
check(q.countUniqueSorted, [[[[1, 1, 2, 3, 3]], 3], [[[]], 0], [[[7]], 1], [[[2, 2, 2]], 1], [[[-3, -1, -1, 0, 4]], 4], [[[1, 2, 3]], 3]]);
check(q.pairWithSum, [
  [[[1, 3, 4, 6, 9], 13], [2, 4]],
  [[[1, 2, 3], 10], null],
  [[[], 5], null],
  [[[5], 10], null],
  [[[2, 5], 7], [0, 1]],
  [[[-4, -1, 2, 8], 1], [1, 2]],
]);
check(q.mergeSorted, [
  [[[1, 4, 7], [2, 3, 8]], [1, 2, 3, 4, 7, 8]],
  [[[], [5]], [5]],
  [[[], []], []],
  [[[1, 2], []], [1, 2]],
  [[[1, 1, 5], [1, 6]], [1, 1, 1, 5, 6]],
  [[[-2, 0], [-5, 10]], [-5, -2, 0, 10]],
]);
check(q.rotateRight, [
  [[[1, 2, 3, 4, 5], 2], [4, 5, 1, 2, 3]],
  [[[1, 2, 3], 4], [3, 1, 2]],
  [[[1, 2, 3], 0], [1, 2, 3]],
  [[[1, 2, 3], 3], [1, 2, 3]],
  [[[], 3], []],
  [[[9], 5], [9]],
]);
