import { check } from "../../scripts/check.js";
import * as q from "./questions.js";

check(q.unique, [[[[3, 1, 3, 2, 1]], [3, 1, 2]], [[[]], []], [[[7]], [7]], [[[5, 5, 5]], [5]], [[["b", "a", "b"]], ["b", "a"]], [[[-1, 0, -1]], [-1, 0]]]);
check(q.hasDuplicate, [[[[1, 2, 3, 1]], true], [[[1, 2, 3]], false], [[[]], false], [[[4]], false], [[["a", "a"]], true], [[[1, "1"]], false]]);
check(q.countDistinct, [[[[1, 2, 2, 3, 3, 3]], 3], [[[]], 0], [[[9]], 1], [[[0, 0, 0]], 1], [[[-2, 2, -2]], 2]]);
check(q.intersection, [
  [[[1, 2, 2, 3], [2, 3, 4]], [2, 3]],
  [[[1, 2], [3]], []],
  [[[], [1, 2]], []],
  [[[1, 2], []], []],
  [[[3, 1, 2], [1, 2, 3]], [3, 1, 2]],
  [[["x", "y", "x"], ["x"]], ["x"]],
]);
check(q.firstRepeated, [[[[2, 5, 1, 5, 2]], 5], [[[1, 2, 3]], null], [[[]], null], [[[8]], null], [[[0, 0]], 0], [[["a", "b", "a"]], "a"]]);
check(q.mostCommon, [
  [[["a", "b", "b", "a", "c", "b"]], "b"],
  [[[1, 2, 2, 1]], 1],
  [[[]], null],
  [[[42]], 42],
  [[[0, 0, 1]], 0],
  [[[3, 1, 2]], 3],
  [[[-1, 5, -1]], -1],
]);
check(q.missingNumber, [[[[1, 2, 4, 5], 5], 3], [[[2, 3, 1], 4], 4], [[[], 1], 1], [[[2], 2], 1], [[[5, 3, 1, 2], 5], 4]]);
check(q.longestUniqueSubstring, [
  [["abcabcbb"], 3],
  [["bbbb"], 1],
  [[""], 0],
  [["a"], 1],
  [["pwwkew"], 3],
  [["abcdef"], 6],
  [["abba"], 2],
  [["dvdf"], 3],
]);
