// Runs firstBadVersion with a counting isBad. fewCalls is true when isBad was called at most about log2(n) times.
function firstBadVersionCalls(n, firstBad) {
  let calls = 0;
  const answer = q.firstBadVersion(n, (v) => {
    calls++;
    return v >= firstBad;
  });
  return { answer, fewCalls: calls <= Math.ceil(Math.log2(n)) + 2 };
}

check(q.firstBadVersion, [
  [[5, (v) => v >= 4], 4],
  [[1, (v) => v >= 1], 1],
  [[2, (v) => v >= 1], 1],
  [[2, (v) => v >= 2], 2],
  [[10, (v) => v >= 10], 10],
  [[10, (v) => v >= 1], 1],
]);
